import { StrictMode } from 'react';
import { createRoot } from 'react-dom/client';
import { BrowserRouter } from 'react-router-dom';
import { QueryClient, QueryClientProvider } from '@tanstack/react-query';
import 'bootstrap/dist/css/bootstrap.min.css';
import './styles/app.css';
import App from './App';
import { AuthProvider } from './context/AuthContext';
import { ThemeProvider } from './context/ThemeContext';
import { ErrorBoundary } from './components/UI';
const queryClient = new QueryClient({ defaultOptions: { queries: { staleTime: 30000, retry: false, refetchOnWindowFocus: false } } });
createRoot(document.getElementById('root')).render(<StrictMode><ErrorBoundary><QueryClientProvider client={queryClient}><ThemeProvider><BrowserRouter><AuthProvider><App/></AuthProvider></BrowserRouter></ThemeProvider></QueryClientProvider></ErrorBoundary></StrictMode>);
